-- V4: User, booking and seat reservation schema

CREATE TABLE app_user (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          display_name VARCHAR(100) NOT NULL,
                          email VARCHAR(255) NOT NULL UNIQUE,
                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT chk_user_display_name
                              CHECK (length(trim(display_name)) > 0),

                          CONSTRAINT chk_user_email
                              CHECK (length(trim(email)) > 0)
);

CREATE TABLE booking (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                         user_id BIGINT NOT NULL,
                         showtime_id BIGINT NOT NULL,

                         status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED',
                         created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         cancelled_at TIMESTAMPTZ,

                         CONSTRAINT fk_booking_user
                             FOREIGN KEY (user_id)
                                 REFERENCES app_user(id)
                                 ON DELETE RESTRICT,

                         CONSTRAINT fk_booking_showtime
                             FOREIGN KEY (showtime_id)
                                 REFERENCES showtime(id)
                                 ON DELETE RESTRICT,

                         CONSTRAINT chk_booking_status
                             CHECK (status IN ('CONFIRMED', 'CANCELLED')),

                         CONSTRAINT chk_booking_cancelled_at
                             CHECK (
                                 (status = 'CONFIRMED' AND cancelled_at IS NULL)
                                     OR
                                 (status = 'CANCELLED' AND cancelled_at IS NOT NULL)
                                 ),

                         CONSTRAINT uq_booking_id_showtime
                             UNIQUE (id, showtime_id)
);

CREATE TABLE booking_seat (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                              booking_id BIGINT NOT NULL,
                              showtime_id BIGINT NOT NULL,
                              hall_id BIGINT NOT NULL,
                              seat_id BIGINT NOT NULL,

                              status VARCHAR(20) NOT NULL DEFAULT 'RESERVED',
                              created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                              cancelled_at TIMESTAMPTZ,

                              CONSTRAINT fk_booking_seat_booking_showtime
                                  FOREIGN KEY (booking_id, showtime_id)
                                      REFERENCES booking(id, showtime_id)
                                      ON DELETE RESTRICT,

                              CONSTRAINT chk_booking_seat_status
                                  CHECK (status IN ('RESERVED', 'CANCELLED')),

                              CONSTRAINT chk_booking_seat_cancelled_at
                                  CHECK (
                                      (status = 'RESERVED' AND cancelled_at IS NULL)
                                          OR
                                      (status = 'CANCELLED' AND cancelled_at IS NOT NULL)
                                      ),

                              CONSTRAINT uq_booking_seat_once
                                  UNIQUE (booking_id, seat_id)
);

-- Composite unique keys allow foreign keys to verify
-- that the seat and showtime belong to the same hall.

ALTER TABLE showtime
    ADD CONSTRAINT uq_showtime_id_hall
        UNIQUE (id, hall_id);

ALTER TABLE seat
    ADD CONSTRAINT uq_seat_id_hall
        UNIQUE (id, hall_id);

ALTER TABLE booking_seat
    ADD CONSTRAINT fk_booking_seat_showtime_hall
        FOREIGN KEY (showtime_id, hall_id)
            REFERENCES showtime(id, hall_id)
            ON DELETE RESTRICT;

ALTER TABLE booking_seat
    ADD CONSTRAINT fk_booking_seat_seat_hall
        FOREIGN KEY (seat_id, hall_id)
            REFERENCES seat(id, hall_id)
            ON DELETE RESTRICT;

-- The core double-booking protection.
CREATE UNIQUE INDEX uq_active_showtime_seat
    ON booking_seat (showtime_id, seat_id)
    WHERE status = 'RESERVED';

CREATE INDEX idx_booking_user_id
    ON booking (user_id);

CREATE INDEX idx_booking_showtime_id
    ON booking (showtime_id);

CREATE INDEX idx_booking_seat_booking_id
    ON booking_seat (booking_id);

CREATE INDEX idx_booking_seat_seat_hall
    ON booking_seat (seat_id, hall_id);
