CREATE TABLE admin_booking_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    booking_id BIGINT NOT NULL,
    admin_user_id BIGINT NOT NULL,

    action VARCHAR(30) NOT NULL,
    reason VARCHAR(500) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_admin_audit_booking
        FOREIGN KEY (booking_id)
            REFERENCES booking(id),

    CONSTRAINT fk_admin_audit_user
        FOREIGN KEY (admin_user_id)
            REFERENCES app_user(id),

    CONSTRAINT chk_admin_audit_action
        CHECK (action IN ('CANCEL')),

    CONSTRAINT chk_admin_audit_reason
        CHECK (length(trim(reason)) BETWEEN 10 AND 500)
);

CREATE INDEX idx_admin_booking_audit_booking
    ON admin_booking_audit (booking_id, created_at DESC);

CREATE INDEX idx_admin_booking_audit_admin
    ON admin_booking_audit (admin_user_id, created_at DESC);