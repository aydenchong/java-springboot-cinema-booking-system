-- V3: Create showtime table and prevent overlapping schedules

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE showtime (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          movie_id BIGINT NOT NULL,
                          hall_id BIGINT NOT NULL,

                          starts_at TIMESTAMPTZ NOT NULL,
                          ends_at TIMESTAMPTZ NOT NULL,

                          status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
                          created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT fk_showtime_movie
                              FOREIGN KEY (movie_id)
                                  REFERENCES movie(id)
                                  ON DELETE RESTRICT,

                          CONSTRAINT fk_showtime_hall
                              FOREIGN KEY (hall_id)
                                  REFERENCES cinema_hall(id)
                                  ON DELETE RESTRICT,

                          CONSTRAINT chk_showtime_time_order
                              CHECK (ends_at > starts_at),

                          CONSTRAINT chk_showtime_status
                              CHECK (status IN ('SCHEDULED', 'CANCELLED')),

                          CONSTRAINT ex_showtime_hall_overlap
                              EXCLUDE USING GIST (
            hall_id WITH =,
            tstzrange(starts_at, ends_at, '[)') WITH &&
        )
        WHERE (status = 'SCHEDULED')
);

CREATE INDEX idx_showtime_movie_id
    ON showtime (movie_id);

CREATE INDEX idx_showtime_hall_starts_at
    ON showtime (hall_id, starts_at);

CREATE INDEX idx_showtime_starts_at
    ON showtime (starts_at);
