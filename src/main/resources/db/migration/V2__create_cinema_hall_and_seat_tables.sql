-- V2: Create cinema halls and their fixed seats

CREATE TABLE cinema_hall (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                             name VARCHAR(100) NOT NULL,
                             hall_type VARCHAR(20) NOT NULL DEFAULT 'STANDARD',
                             created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                             CONSTRAINT uq_cinema_hall_name
                                 UNIQUE (name),

                             CONSTRAINT chk_cinema_hall_name
                                 CHECK (length(trim(name)) > 0),

                             CONSTRAINT chk_cinema_hall_type
                                 CHECK (hall_type IN ('STANDARD', 'IMAX', 'VIP'))
);

CREATE TABLE seat (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                      hall_id BIGINT NOT NULL,
                      row_label VARCHAR(5) NOT NULL,
                      seat_number INTEGER NOT NULL,

                      CONSTRAINT fk_seat_hall
                          FOREIGN KEY (hall_id)
                              REFERENCES cinema_hall(id)
                              ON DELETE RESTRICT,

                      CONSTRAINT chk_seat_row_label
                          CHECK (length(trim(row_label)) > 0),

                      CONSTRAINT chk_seat_number
                          CHECK (seat_number > 0),

                      CONSTRAINT uq_seat_hall_position
                          UNIQUE (hall_id, row_label, seat_number)
);

CREATE INDEX idx_seat_hall_id
    ON seat (hall_id);
